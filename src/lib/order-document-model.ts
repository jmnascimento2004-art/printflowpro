export function documentDate(value?: string | null) {
  if (!value) return '';
  const date = new Date(/^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value}T12:00:00-03:00` : value);
  return Number.isNaN(date.getTime()) ? '' : date.toLocaleDateString('pt-BR', { timeZone: 'America/Bahia' });
}

// Only explicitly commercial configuration fields cross the document boundary.
// In particular, free notes, pricing breakdowns and supplier costs do not.
export function documentItem(item: OrderItem) {
  const details = item.details || {};
  const config = details.configuration_snapshot;
  const fields = details.pricing_snapshot?.custom_fields;
  const selected = (Array.isArray(details.selected_options) ? details.selected_options : []).flatMap(option => option && typeof option === 'object'
    ? [[option.group_name, option.option_name || option.name].filter(value => typeof value === 'string' && value).join(': ')] : []);
  const structured = [config?.material, config?.colors, config?.finishing, details.variant, details.color, ...selected,
    ...(Array.isArray(fields) ? fields.flatMap(field => {
      if (!field || typeof field !== 'object') return [];
      const { label, value, type } = field;
      return typeof label === 'string' && ['string', 'number', 'boolean'].includes(typeof value)
        ? [`${label}: ${typeof value === 'boolean' ? value ? 'Sim' : 'Não' : String(value)}${type === 'measure' ? ' m' : ''}`] : [];
    }) : [])].filter(value => typeof value === 'string' && value).join(' · ');
  // This dedicated summary is generated by the product configurator from
  // configuration/dimensions only; free operational notes use a different field.
  const configuration = structured || (typeof details.configuration_summary === 'string' ? cleanLegacyGeneratedDescription(details.configuration_summary) : '');
  const model = buildPdfItemViewModel({ ...item, details: { ...details, pricing_snapshot: { size: typeof details.pricing_snapshot?.size === 'string' ? details.pricing_snapshot.size : '' } } });
  const w = Number(details.width), h = Number(details.height);
  const number = (n: number) => n.toLocaleString('pt-BR', { maximumFractionDigits: 3 });
  const area = w > 0 && h > 0 ? `${number(w * h)} m² por peça` : '';
  return { id: item.id, name: cleanLegacyGeneratedDescription(item.product_name),
    configuration, measures: [model.size === '—' ? '' : model.size, area].filter(Boolean).join(' · '),
    quantity: model.quantity, unit: model.unitPrice, total: model.totalPrice };
}

export function commercialSummary(order: { items: Array<{ total_price: number }>; additional_services?: Array<{ total_price: number }>; shipping_cost?: number; total_amount: number }) {
  const items = order.items.reduce((sum, item) => sum + Number(item.total_price || 0), 0);
  const services = (order.additional_services || []).reduce((sum, item) => sum + Number(item.total_price || 0), 0);
  const freight = Number(order.shipping_cost || 0);
  const adjustment = Math.round((Number(order.total_amount) - items - services - freight) * 100) / 100;
  return { items, services, freight, discount: Math.max(0, -adjustment), adjustment: Math.max(0, adjustment), total: Number(order.total_amount) };
}
